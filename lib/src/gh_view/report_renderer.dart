/// Renders GitHub Flavored Markdown report.
String renderMarkdownReport(List<GhPr> prs, {DateTime? currentTime}) {
  final now = currentTime ?? DateTime.now();
  final categorized = categorizePullRequests(prs);

  final home = Platform.environment['HOME'] ?? '/usr/local/google/home/kevmoo';
  final link = 'file://$home/github/kevmoo/scripts.dart/bin/gh_view.dart';
  final buffer = StringBuffer()
    ..writeln('# 🐙 GitHub Pull Request Overview Dashboard')
    ..writeln()
    ..writeln(
      'Generated by [`gh-view`]($link) | Scope: `@me` (All GitHub Orgs)',
    )
    ..writeln()
    ..writeln('---')
    ..writeln()
    ..writeln('## 📊 High-Level Summary')
    ..writeln()
    ..writeln('| Metric | Count | Status Description |')
    ..writeln('| :--- | :---: | :--- |')
    ..writeln(
      '| **Total Open PRs** | **${prs.length}** | '
      'Active pull requests across all GitHub organizations |',
    )
    ..writeln(
      '| 🚀 **Ready to Merge** | **${categorized.readyToMerge.length}** | '
      'Approved by reviewers, passing all CI checks, and mergeable |',
    )
    ..writeln(
      '| ⚠️ **Action Needed** | **${categorized.actionNeeded.length}** | '
      'Blocked by failing CI, changes requested, or merge conflicts |',
    )
    ..writeln(
      '| 🟡 **In Review Queue** | **${categorized.inReview.length}** | '
      'Active non-draft PRs with green/pending CI awaiting review |',
    )
    ..writeln(
      '| ⚪ **Drafts & WIP** | **${categorized.drafts.length}** | '
      'Work-in-progress draft pull requests |',
    )
    ..writeln(
      '| 📦 **Archived Repositories** | **${categorized.archived.length}** | '
      'Pull requests in archived/read-only repositories |',
    )
    ..writeln();

  if (prs.isEmpty) {
    buffer.writeln('No open pull requests found. 🎉\n');
    return buffer.toString();
  }

  _writeMarkdownSection(
    buffer,
    title: '## 🚀 1. Ready to Merge (Approved + Green CI + Mergeable)',
    prs: categorized.readyToMerge,
    now: now,
  );

  _writeMarkdownSection(
    buffer,
    title:
        '## ⚠️ 2. Action Needed '
        '(Blocked / Failing CI / Conflicts / Changes Requested)',
    prs: categorized.actionNeeded,
    now: now,
  );

  _writeMarkdownSection(
    buffer,
    title: '## 🟡 3. In Review Queue (Green CI + Active Review)',
    prs: categorized.inReview,
    now: now,
  );

  _writeMarkdownSection(
    buffer,
    title:
        '## ⚪ 4. Drafts & Work In Progress (${categorized.drafts.length} PRs)',
    prs: categorized.drafts,
    now: now,
  );

  _writeMarkdownSection(
    buffer,
    title:
        '## 📦 5. Archived Repositories (Read-Only) '
        '(${categorized.archived.length} PRs)',
    prs: categorized.archived,
    now: now,
  );

  return buffer.toString();
}

void _writeMarkdownSection(
  StringBuffer buffer, {
  required String title,
  required List<GhPr> prs,
  required DateTime now,
}) {
  if (prs.isEmpty) return;
  const tableHeader = '''
| PR & Repository | Branch & Local Mapping | Review & CI Status | Last Touched | Action / Ping Status |
| :--- | :--- | :--- | :--- | :--- |''';

  buffer
    ..writeln(title)
    ..writeln()
    ..writeln(tableHeader);
  for (final pr in prs) {
    _writeMarkdownPrRow(buffer, pr, now);
  }
  buffer.writeln();
}

void _writeMarkdownPrRow(StringBuffer buffer, GhPr pr, DateTime now) {
  final repoUrl = pr.repoUrl.isNotEmpty
      ? pr.repoUrl
      : 'https://github.com/${pr.repository}';
  final queuePrefix = pr.isInMergeQueue ? '`[🔀 Merge Queue]` ' : '';
  final sanitizedTitle = sanitizeMarkdownCell(pr.title);

  final prLines = <String>[
    if (pr.context != null && pr.context!.trim().isNotEmpty) ...[
      sanitizeMarkdownCell(pr.context!, newlinesToBr: true),
      '',
    ],
    '[#${pr.number}](${pr.url}) $queuePrefix$sanitizedTitle',
    '[${pr.repository}]($repoUrl)',
  ];

  final loc = pr.localStatus;
  final localMapping = loc == null
      ? 'Local: ⚪ Not checked out'
      : 'Local: ${loc.displayStatus} '
            '([${p.basename(loc.repoPath)}](file://${loc.repoPath}))';
  final branchLines = <String>['`${pr.headRefName}`', localMapping];

  final areThreadsResolved =
      pr.totalReviewThreads > 0 &&
      pr.unresolvedReviewerThreads == 0 &&
      pr.unresolvedAuthorThreads == 0;
  final isReady = isReadyToMerge(pr);

  final statusLines = <String>[
    'Review: ${_formatReviewBadgeMarkdown(pr, areThreadsResolved)}',
    'CI: ${_formatCiBadgeMarkdown(pr.ciStatus)}',
    'Merge: ${_formatMergeableBadgeMarkdown(pr)}',
  ];

  final touched = formatTouchedMarkdown(pr.updatedAt, currentTime: now);
  final actionItem = _resolveActionItemMarkdown(
    pr,
    areThreadsResolved: areThreadsResolved,
    isReadyToMerge: isReady,
    now: now,
  );

  final prCell = prLines.join('<br>');
  final branchCell = branchLines.join('<br>');
  final statusCell = statusLines
      .map((line) => line.replaceAll(' ', '&nbsp;'))
      .join('<br>');

  buffer.writeln(
    '| $prCell | $branchCell | $statusCell | $touched | $actionItem |',
  );
}

String _resolveActionItemMarkdown(
  GhPr pr, {
  required bool areThreadsResolved,
  required bool isReadyToMerge,
  required DateTime now,
}) {
  if (pr.isRepoArchived) return '📦 Archived repo (read-only)';
  if (isReadyToMerge) return '🚀 **Ready to merge**';
  if (pr.isBlockedByProtection) {
    return '🧱 **Blocked by ruleset/branch protection**';
  }

  final reviewers = pr.targetReviewers;
  final hasReviewers = reviewers.isNotEmpty;
  final reviewersText = hasReviewers ? '@${reviewers.join(', @')}' : '';
  final hasRequestedReviewers =
      pr.requestedReviewers.isNotEmpty && pr.unrequestedActiveReviewers.isEmpty;

  if (pr.mergeable != MergeableState.conflicting &&
      pr.ciStatus == CiStatus.actionRequired) {
    return _formatCiActionMarkdown(pr);
  }

  return switch ((
    pr.mergeable == MergeableState.conflicting,
    pr.ciStatus == CiStatus.failure,
    pr.effectiveReviewDecision,
    pr.isDraft,
  )) {
    (true, _, _, true) => '⚠️ **Conflicting** (draft)',
    (true, _, _, false) => '⚠️ **Conflicting** (needs rebase)',
    (_, true, _, _) => _formatCiFailingMarkdown(pr),
    (_, _, ReviewDecision.approved, false)
        when pr.unresolvedReviewerThreads > 0 =>
      '❌ **Address ${pr.unresolvedReviewerThreads} unresolved comment(s)**',
    (_, _, ReviewDecision.changesRequested, _) =>
      _formatChangesRequestedActionMarkdown(
        pr,
        reviewersText: reviewersText,
        hasRequestedReviewers: hasRequestedReviewers,
        areThreadsResolved: areThreadsResolved,
      ),
    (_, _, ReviewDecision.reviewRequired || ReviewDecision.none, _) =>
      _resolveReviewRequiredActionMarkdown(
        pr,
        reviewersText: reviewersText,
        areThreadsResolved: areThreadsResolved,
        now: now,
      ),
    (_, _, _, true) => '⚪ **Work in progress**',
    _ => '⚪ **Active**',
  };
}

String _formatCiActionMarkdown(GhPr pr) {
  final detail = _sanitizeMarkdownCellDetail(pr.ciDetail);
  if (detail != null) {
    final prefix = pr.isDraft ? 'draft · ' : '';
    return '🟠 **CI Action Required** ($prefix$detail)';
  }
  return pr.isDraft
      ? '🟠 **CI Action Required** (draft)'
      : '🟠 **CI Action Required** (needs manual trigger/approval)';
}

String _formatCiFailingMarkdown(GhPr pr) {
  final detail = _sanitizeMarkdownCellDetail(pr.ciDetail);
  if (detail != null) {
    final prefix = pr.isDraft ? 'draft · ' : '';
    return '🔴 **CI Failing** ($prefix$detail)';
  }
  return pr.isDraft
      ? '🔴 **CI Failing** (draft)'
      : '🔴 **CI Failing** (needs fix)';
}

String? _sanitizeMarkdownCellDetail(String? detail) {
  if (detail == null) return null;
  final cleaned = sanitizeMarkdownCell(detail);
  return cleaned.isEmpty ? null : cleaned;
}

String _formatQueuedChangesRequestedAction(GhPr pr, String reviewersText) {
  if (pr.approvedReviewers.isEmpty) {
    return '🟡 **Re-review Requested** ($reviewersText)';
  }
  final approvers = '@${pr.approvedReviewers.join(', @')}';
  return '🟡 **Approved ($approvers)** · Awaiting $reviewersText '
      '(or dismiss stale CR)';
}

String _formatChangesRequestedActionMarkdown(
  GhPr pr, {
  required String reviewersText,
  required bool hasRequestedReviewers,
  required bool areThreadsResolved,
}) {
  if (pr.needsReviewReRequest) {
    return '🔄 **Re-request Review** '
        '(@${pr.unrequestedActiveReviewers.join(', @')})';
  }
  if (hasRequestedReviewers) {
    return _formatQueuedChangesRequestedAction(pr, reviewersText);
  }
  if (areThreadsResolved && pr.hasAuthorRespondedSinceLastReview) {
    return '🔄 **Re-review Needed** (threads resolved)';
  }
  final crReviewers = pr.changesRequestedReviewers;
  final crReviewersText = crReviewers.isNotEmpty
      ? '@${crReviewers.join(', @')}'
      : '';
  if (pr.unresolvedReviewerThreads > 0 || pr.unresolvedAuthorThreads > 0) {
    final suffix = crReviewersText.isNotEmpty ? ' · $crReviewersText' : '';

    return '🔴 **Changes Requested** '
        '(${pr.unresolvedReviewerThreads} reviewer open, '
        '${pr.unresolvedAuthorThreads} author-replied open$suffix)';
  }
  return crReviewersText.isNotEmpty
      ? '🔴 **Changes Requested** ($crReviewersText)'
      : '🔴 **Changes Requested**';
}

String _resolveReviewRequiredActionMarkdown(
  GhPr pr, {
  required String reviewersText,
  required bool areThreadsResolved,
  required DateTime now,
}) {
  if (pr.unresolvedReviewerThreads > 0) {
    return pr.isDraft
        ? '⚪ **Work in progress** (${pr.unresolvedReviewerThreads} unresolved)'
        : '❌ **Address ${pr.unresolvedReviewerThreads} unresolved comment(s)**';
  }
  if (pr.needsReviewReRequest) {
    final unrequestedText = '@${pr.unrequestedActiveReviewers.join(', @')}';
    return '🔄 **Re-request Review** ($unrequestedText)';
  }
  final authorComment = pr.lastAuthorCommentAt;
  if (pr.isAlreadyPinged &&
      authorComment != null &&
      now.difference(authorComment).inDays < 7) {
    final pingAge = formatTimeAgo(authorComment, currentTime: now);
    if (reviewersText.isNotEmpty) {
      return '⏳ **Awaiting $reviewersText** (pinged $pingAge)';
    }
    return '⏳ **Awaiting Review** (pinged $pingAge)';
  }
  if (areThreadsResolved) {
    if (reviewersText.isNotEmpty) {
      return '🔔 **Ping Reviewer** ($reviewersText)';
    }
    return '👤 **Request Reviewer** (threads resolved, none in queue)';
  }
  if (reviewersText.isNotEmpty) {
    return '⏳ **Awaiting $reviewersText**';
  }
  if (pr.isDraft) {
    return '⚪ **Work in progress**';
  }
  return '👤 **Request Reviewer** (none in queue)';
}

String _formatChangesRequestedBadgeMarkdown(GhPr pr, bool areThreadsResolved) {
  if (pr.unresolvedReviewerThreads > 0) {
    return '🔴 Changes Requested (${pr.unresolvedReviewerThreads} unresolved)';
  }
  if (pr.needsReviewReRequest) {
    return '🔴 Changes Requested · Re-request '
        '(@${pr.unrequestedActiveReviewers.join(', @')})';
  }
  if (pr.requestedReviewers.isNotEmpty &&
      pr.unrequestedActiveReviewers.isEmpty) {
    final reReview =
        '🟡 Re-review Requested (@${pr.targetReviewers.join(', @')})';
    return pr.approvedReviewers.isEmpty
        ? reReview
        : '$reReview · 🟢 Approved (@${pr.approvedReviewers.join(', @')})';
  }
  if (areThreadsResolved && pr.hasAuthorRespondedSinceLastReview) {
    return '🔴 Changes Requested (Resolved)';
  }
  if (pr.unresolvedAuthorThreads > 0) {
    return '🔴 Changes Requested (${pr.unresolvedAuthorThreads} open)';
  }
  if (pr.changesRequestedReviewers.isNotEmpty) {
    return '🔴 Changes Requested '
        '(@${pr.changesRequestedReviewers.join(', @')})';
  }
  return '🔴 Changes Requested';
}

String _formatPendingReviewBadgeMarkdown(GhPr pr) {
  if (!pr.isDraft && pr.unresolvedReviewerThreads > 0) {
    return '❌ Unresolved Comments (${pr.unresolvedReviewerThreads})';
  }
  if (pr.needsReviewReRequest) {
    return '🟠 Re-request Review '
        '(@${pr.unrequestedActiveReviewers.join(', @')})';
  }
  if (pr.effectiveReviewDecision == ReviewDecision.reviewRequired) {
    return pr.targetReviewers.isNotEmpty
        ? '🟡 Review Required (@${pr.targetReviewers.join(', @')})'
        : '🟡 Review Required';
  }
  return '⚪ None';
}

String _formatReviewBadgeMarkdown(GhPr pr, bool areThreadsResolved) =>
    switch (pr.effectiveReviewDecision) {
      ReviewDecision.approved =>
        pr.unresolvedReviewerThreads > 0
            ? '🟠 Approved (${pr.unresolvedReviewerThreads} unresolved)'
            : '🟢 Approved',
      ReviewDecision.changesRequested => _formatChangesRequestedBadgeMarkdown(
        pr,
        areThreadsResolved,
      ),
      _ => _formatPendingReviewBadgeMarkdown(pr),
    };

String _formatCiBadgeMarkdown(CiStatus ciStatus) => switch (ciStatus) {
  CiStatus.success => '🟢 Passing',
  CiStatus.treeBroken => '🟠 Tree Broken (PR Clean)',
  CiStatus.actionRequired => '🟠 Action Required',
  CiStatus.failure => '🔴 Failing',
  CiStatus.pending => '⏳ Pending',
  _ => '⚪ None',
};

String _formatMergeableBadgeMarkdown(GhPr pr) {
  if (pr.isBlockedMergeState) {
    return '🧱 Blocked';
  }

  final label = switch (pr.mergeable) {
    MergeableState.mergeable => '✅ Yes',
    MergeableState.conflicting => '⚠️ Conflicting',
    _ => pr.isInMergeQueue ? '✅ Yes' : '⚪ Unknown',
  };
  return pr.isInMergeQueue ? '$label (🔀 Queue)' : label;
}

/// Renders human-readable colorized terminal output.
String renderTerminalReport(List<GhPr> prs, {DateTime? currentTime}) {
  final now = currentTime ?? DateTime.now();
  final categorized = categorizePullRequests(prs);

  final buffer = StringBuffer()
    ..writeln('''
======================================================================
${styleBold.wrap('🐙 GITHUB PULL REQUEST OVERVIEW')}
======================================================================''');

  if (prs.isEmpty) {
    buffer.writeln('\nNo open pull requests found. 🎉\n');
    return buffer.toString();
  }

  _writeTerminalSection(
    buffer,
    title: green.wrap(styleBold.wrap('🚀 READY TO MERGE')!)!,
    subtitle: 'Approved by reviewers and all CI checks passing:',
    prs: categorized.readyToMerge,
    now: now,
  );

  _writeTerminalSection(
    buffer,
    title: red.wrap(
      styleBold.wrap('⚠️  ACTION NEEDED (Blocked / Failing / Conflicts)')!,
    )!,
    subtitle: 'Requires code fixes, rebase, or review feedback resolution:',
    prs: categorized.actionNeeded,
    now: now,
  );

  _writeTerminalSection(
    buffer,
    title: yellow.wrap(styleBold.wrap('🟡 IN REVIEW QUEUE')!)!,
    subtitle: 'Active PRs awaiting reviewer feedback:',
    prs: categorized.inReview,
    now: now,
  );

  _writeTerminalSection(
    buffer,
    title: styleDim.wrap(styleBold.wrap('⚪ DRAFTS & WORK IN PROGRESS')!)!,
    subtitle: 'Work-in-progress draft pull requests:',
    prs: categorized.drafts,
    now: now,
  );

  _writeTerminalSection(
    buffer,
    title: styleDim.wrap(
      styleBold.wrap('📦 ARCHIVED REPOSITORIES (Read-Only)')!,
    )!,
    subtitle: 'Repositories are archived; pull requests cannot be modified:',
    prs: categorized.archived,
    now: now,
  );

  final summary =
      'Total Open: ${prs.length} | '
      '🚀 Ready: ${categorized.readyToMerge.length} | '
      '⚠️ Action: ${categorized.actionNeeded.length} | '
      '🟡 Review: ${categorized.inReview.length} | '
      '⚪ Drafts: ${categorized.drafts.length} | '
      '📦 Archived: ${categorized.archived.length}';

  buffer.writeln('''

----------------------------------------------------------------------
${styleBold.wrap('Summary:')} $summary
----------------------------------------------------------------------''');

  return buffer.toString();
}

void _writeTerminalSection(
  StringBuffer buffer, {
  required String title,
  required String subtitle,
  required List<GhPr> prs,
  required DateTime now,
}) {
  if (prs.isEmpty) return;
  buffer
    ..writeln('\n$title')
    ..writeln(styleDim.wrap('   $subtitle')!);
  for (final pr in prs) {
    _writePrItem(buffer, pr, now);
  }
}

void _writePrItem(StringBuffer buffer, GhPr pr, DateTime now) {
  final prTag =
      styleBold.wrap('${pr.repository}#${pr.number}') ??
      '${pr.repository}#${pr.number}';
  final touched = formatTouchedTerminal(pr.updatedAt, currentTime: now);

  final statusBadges = <String>[];
  if (pr.isRepoArchived) {
    statusBadges.add(styleDim.wrap('[Archived Repo]') ?? '[Archived Repo]');
  }
  if (pr.isDraft) {
    statusBadges.add(styleDim.wrap('[Draft]') ?? '[Draft]');
  }

  statusBadges
    ..add(_formatReviewBadgeTerminal(pr))
    ..add(_formatCiBadgeTerminal(pr));
  if (pr.isInMergeQueue) {
    statusBadges.add(cyan.wrap('🔀 In Merge Queue') ?? '🔀 In Merge Queue');
  }
  if (pr.isBlockedMergeState) {
    statusBadges.add(red.wrap('🧱 Blocked') ?? '🧱 Blocked');
  }
  if (pr.mergeable == MergeableState.conflicting) {
    statusBadges.add(red.wrap('⚠️ Conflicting') ?? '⚠️ Conflicting');
  }

  buffer
    ..writeln('\n  • $prTag: ${pr.title}')
    ..writeln('    URL:     ${pr.url}')
    ..writeln('    Status:  ${statusBadges.join(' | ')}')
    ..writeln('    Branch:  ${pr.headRefName} ➔ ${pr.baseRefName}')
    ..writeln('    Touched: $touched');

  if (pr.mergeable == MergeableState.conflicting) {
    final conflictLine =
        red.wrap(
          '⚠️ Blocked by merge conflicts with origin/${pr.baseRefName} '
          '(run: git fetch origin ${pr.baseRefName} && git merge origin/${pr.baseRefName})',
        ) ??
        '⚠️ Blocked by merge conflicts with origin/${pr.baseRefName} '
            '(run: git fetch origin ${pr.baseRefName} && git merge origin/${pr.baseRefName})';
    buffer.writeln('    Merge:   $conflictLine');
  }

  if (pr.ciDetail != null && pr.ciDetail!.trim().isNotEmpty) {
    buffer.writeln('    Checks:  ${pr.ciDetail!.trim()}');
  }

  if (pr.context != null && pr.context!.trim().isNotEmpty) {
    buffer.writeln('    Context: ${pr.context!.trim()}');
  }

  if (pr.localStatus != null) {
    final loc = pr.localStatus!;
    final locDesc = p.basename(loc.repoPath);
    final wtTag = loc.isWorktree ? ' (worktree)' : '';
    buffer.writeln(
      '    Local:   ${loc.displayStatus} [$locDesc$wtTag at ${loc.repoPath}]',
    );
  }
}

String _formatTerminalRequestedBadge(
  GhPr pr,
  String label, [
  List<String>? list,
]) {
  final targets = list ?? pr.targetReviewers;
  final text = targets.isNotEmpty ? '$label (@${targets.join(', @')})' : label;
  return yellow.wrap(text) ?? text;
}

String _formatTerminalQueuedChangesRequestedBadge(GhPr pr) {
  final reReviewText = _formatTerminalRequestedBadge(pr, 'Re-review Requested');
  if (pr.approvedReviewers.isEmpty) return reReviewText;
  final approvers = '@${pr.approvedReviewers.join(', @')}';
  final approvedText =
      green.wrap('Approved ($approvers)') ?? 'Approved ($approvers)';
  return '$reReviewText · $approvedText';
}

String _formatChangesRequestedBadgeTerminal(GhPr pr) {
  if (pr.unresolvedReviewerThreads > 0) {
    final label =
        'Changes Requested (${pr.unresolvedReviewerThreads} unresolved)';
    return red.wrap(label) ?? label;
  }
  if (pr.needsReviewReRequest) {
    return _formatTerminalRequestedBadge(
      pr,
      'Changes Requested · Re-request',
      pr.unrequestedActiveReviewers,
    );
  }
  if (pr.requestedReviewers.isNotEmpty &&
      pr.unrequestedActiveReviewers.isEmpty) {
    return _formatTerminalQueuedChangesRequestedBadge(pr);
  }
  if (pr.totalReviewThreads > 0 &&
      pr.unresolvedReviewerThreads == 0 &&
      pr.unresolvedAuthorThreads == 0 &&
      pr.hasAuthorRespondedSinceLastReview) {
    const label = 'Changes Requested (Resolved: Re-review Needed)';
    return yellow.wrap(label) ?? label;
  }
  final crReviewers = pr.changesRequestedReviewers;
  final label = crReviewers.isNotEmpty
      ? 'Changes Requested (@${crReviewers.join(', @')})'
      : 'Changes Requested';
  return red.wrap(label) ?? label;
}

String _formatPendingReviewBadgeTerminal(GhPr pr) {
  if (!pr.isDraft && pr.unresolvedReviewerThreads > 0) {
    final label = 'Unresolved Comments (${pr.unresolvedReviewerThreads})';
    return red.wrap(label) ?? label;
  }
  if (pr.needsReviewReRequest) {
    return _formatTerminalRequestedBadge(
      pr,
      'Re-request Review',
      pr.unrequestedActiveReviewers,
    );
  }
  if (pr.effectiveReviewDecision == ReviewDecision.reviewRequired) {
    return _formatTerminalRequestedBadge(pr, 'Review Required');
  }
  return 'No Reviewers';
}

String _formatReviewBadgeTerminal(GhPr pr) =>
    switch (pr.effectiveReviewDecision) {
      ReviewDecision.approved when pr.unresolvedReviewerThreads > 0 =>
        yellow.wrap('Approved (${pr.unresolvedReviewerThreads} unresolved)') ??
            'Approved (${pr.unresolvedReviewerThreads} unresolved)',
      ReviewDecision.approved when pr.mergeable == MergeableState.conflicting =>
        green.wrap('Approved (Conflicting)') ?? 'Approved (Conflicting)',
      ReviewDecision.approved => green.wrap('Approved') ?? 'Approved',
      ReviewDecision.changesRequested => _formatChangesRequestedBadgeTerminal(
        pr,
      ),
      _ => _formatPendingReviewBadgeTerminal(pr),
    };

String _formatCiBadgeTerminal(GhPr pr) => switch (pr.ciStatus) {
  CiStatus.success => green.wrap('CI: Passing') ?? 'CI: Passing',
  CiStatus.treeBroken =>
    yellow.wrap('CI: Tree Broken (PR Clean)') ?? 'CI: Tree Broken (PR Clean)',
  CiStatus.actionRequired =>
    yellow.wrap('CI: Action Required') ?? 'CI: Action Required',
  CiStatus.failure => red.wrap('CI: Failing') ?? 'CI: Failing',
  CiStatus.pending => yellow.wrap('CI: Pending') ?? 'CI: Pending',
  _ => styleDim.wrap('CI: None') ?? 'CI: None',
};

/// Renders machine-readable JSON output.
String renderJsonOutput(List<GhPr> prs, {DateTime? currentTime}) {
  final now = currentTime ?? DateTime.now();
  final categorized = categorizePullRequests(prs);

  Map<String, dynamic> prToJson(GhPr pr, String category) => {
    'category': category,
    'number': pr.number,
    'title': pr.title,
    'url': pr.url,
    'author': pr.author,
    'repository': pr.repository,
    'repoUrl': pr.repoUrl,
    'isRepoArchived': pr.isRepoArchived,
    'isDraft': pr.isDraft,
    'state': pr.state,
    'reviewDecision': pr.effectiveReviewDecision,
    'requestedReviewers': pr.requestedReviewers,
    'activeReviewers': pr.activeReviewers,
    'approvedReviewers': pr.approvedReviewers,
